#!/usr/bin/env bash
# Run in the foreground of a long-lived CPU RJob.
set -euo pipefail

config_dir=${1:?Pass the directory generated by deepseek_serving.py router}
haproxy_bin=${HAPROXY_BIN:-haproxy}
python_bin=${PYTHON_BIN:-python3}

"$haproxy_bin" -c -f "$config_dir/workers.cfg"
"$haproxy_bin" -W -db -f "$config_dir/workers.cfg" &
haproxy_pid=$!
"$python_bin" -c 'import json, os, sys; argv = json.load(open(sys.argv[1])); os.execv(argv[0], argv)' \
  "$config_dir/smg-argv.json" &
router_pid=$!

drain() {
  trap '' TERM INT
  kill -TERM "$router_pid" 2>/dev/null || true
  wait "$router_pid" 2>/dev/null || true
  kill -USR1 "$haproxy_pid" 2>/dev/null || true
  wait "$haproxy_pid" 2>/dev/null || true
}

trap 'drain; exit 0' TERM INT
wait -n "$haproxy_pid" "$router_pid" || true
drain
# An unexpected exit requires the RJob restart policy, even if a child exited zero.
exit 1
